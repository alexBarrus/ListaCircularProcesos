    /** Valida el formulario antes de crear el record; null si algo esta mal. */
    private Proceso leerProceso() {
        Integer pid = leerEntero(txtPid, "PID");
        if (pid == null) {
            return null;
        }
        if (pid <= 0) {
            aviso("El PID debe ser mayor que 0.");
            return null;
        }
        String nombre = txtNombre.getText().trim();
        if (nombre.isEmpty()) {
            aviso("Escriba el nombre del proceso.");
            txtNombre.requestFocus();
            return null;
        }
        Integer rafaga = leerEntero(txtRafaga, "Ráfaga");
        if (rafaga == null) {
            return null;
        }
        if (rafaga <= 0) {
            aviso("La ráfaga debe ser mayor que 0.");
            return null;
        }
        if (lista.contiene(pid)) {
            aviso("Ya existe un proceso con PID " + pid + ".");
            return null;
        }
        return new Proceso(pid, nombre, rafaga);
    }

    /** Convierte el texto de un campo a entero o avisa del error de formato. */
    private Integer leerEntero(javax.swing.JTextField campo, String nombreCampo) {
        String texto = campo.getText().trim();
        if (texto.isEmpty()) {
            aviso("El campo \"" + nombreCampo + "\" está vacío.");
            campo.requestFocus();
            return null;
        }
        try {
            return Integer.valueOf(texto);
        } catch (NumberFormatException ex) {
            aviso("\"" + texto + "\" no es un número entero válido para " + nombreCampo + ".");
            campo.requestFocus();
            return null;
        }
    }

    private void terminarInsercion(String donde) {
        txtPid.setText("");
        txtNombre.setText("");
        txtRafaga.setText("");
        txtPid.requestFocus();
        actualizarVista();
        JOptionPane.showMessageDialog(this, "Proceso insertado " + donde + ".");
    }

    private void informarRemovido(Proceso p) {
        actualizarVista();
        JOptionPane.showMessageDialog(this, "Se removió:\n" + p, "Remover",
                JOptionPane.INFORMATION_MESSAGE);
    }

    private void aviso(String mensaje) {
        JOptionPane.showMessageDialog(this, mensaje, "Aviso", JOptionPane.WARNING_MESSAGE);
    }

    /** Vuelve a llenar la tabla, el nodo actual y el estado del anillo. */
    private void actualizarVista() {
        modeloTabla.setRowCount(0);
        for (int i = 0; i < lista.getTamanio(); i++) {
            Proceso p = lista.obtener(i);
            modeloTabla.addRow(new Object[]{i, p.pid(), p.nombre(), p.rafaga()});
        }

        if (lista.estaVacia()) {
            txtActual.setText("La lista está vacía.");
            lblPosicionActual.setText("Sin nodo actual");
            lblAnillo.setText("Procesos: 0   |   primero = null   |   ultimo = null");
            return;
        }

        int pos = lista.getPosicionActual();
        String extremo = "";
        if (pos == 0 && lista.getTamanio() == 1) {
            extremo = "  (primero y último)";
        } else if (pos == 0) {
            extremo = "  (primero)";
        } else if (pos == lista.getTamanio() - 1) {
            extremo = "  (último)";
        }
        txtActual.setText(lista.getActual().toString());
        lblPosicionActual.setText("Posición actual: " + pos + " de " + (lista.getTamanio() - 1) + extremo);
        tablaProcesos.setRowSelectionInterval(pos, pos);

        lblAnillo.setText("Procesos: " + lista.getTamanio()
                + "   |   último.siguiente → PID " + lista.siguienteDelUltimo().pid()
                + "   |   primero.anterior → PID " + lista.anteriorDelPrimero().pid());
    }

